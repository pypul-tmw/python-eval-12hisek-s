for i in range(1,10):
    #sequence of numbers from 1 to 9
    print(i)

print("sequence of numbers from 1 to 8, in increments of 2")
for i in range(1,9,2):
    #sequence of numbers from 1 to 8, in increments of 2
    print(i)

print("sequence of numbers from 1 to 8, in decrements of 2")
for i in range(10,0,-2):
    #sequence of numbers from 1 to 8, in decrements of 2
    print(i)